"""Generate docs/agent_tools.md, the tool reference, from the server itself (run in the agent venv).

    artpipe agent docs [--check]

Every tool's name, description and input schema come from the live tool list
(the same list a client gets), so the reference can't drift from the code;
--check exits 1 if the file is stale (a test runs it).
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "agent_tools.md"

HEADER = """# artpipe MCP tools (generated)

Generated by `artpipe agent docs` from the server's own tool list: do not edit
by hand. The guide is [agent.md](agent.md). Exit codes in every result: 0 pass,
1 the asset failed its checks or was handed over, 2 tool error. Gated actions
(writes outside `out/`) are not tools: they go through `queue_request`.

"""

GROUPS = [
    ("Session", ["artpipe_info", "read_conventions", "read_report"]),
    ("Jobs", ["job_status", "job_result", "job_cancel", "job_list"]),
    ("Maya assets", ["list_checks", "run_check", "apply_fix", "validate", "texture_check"]),
    ("Generation", ["gen_concept", "gen_model", "gen_ingest"]),
    ("Banners", ["banners_kit", "banners_render", "banners_check", "banners_batch"]),
    ("Unity", ["unity_verify"]),
    ("Approval queue", ["queue_request", "queue_list", "queue_get", "queue_run"]),
    ("Judgement", ["review_concept", "review_banner", "review_image", "record_review", "retry_concept"]),
]


def _param_rows(schema):
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    rows = []
    for name, spec in props.items():
        typ = spec.get("type") or "/".join(t.get("type", "?") for t in spec.get("anyOf", [])) or "?"
        default = "" if name in required else "default `%s`" % json.dumps(spec.get("default"))
        rows.append("| `%s` | %s | %s | %s |" % (name, typ, "yes" if name in required else "", default))
    return rows


async def _tools():
    from agent.server import server
    return await server.list_tools()


def render() -> str:
    tools = {t.name: t for t in asyncio.run(_tools())}
    grouped = [n for _, names in GROUPS for n in names]
    missing = sorted(set(tools) - set(grouped))
    if missing:
        raise SystemExit("tools not in a docs group: %s (add them to agent/docs.py GROUPS)" % ", ".join(missing))
    out = [HEADER]
    for title, names in GROUPS:
        out.append("## %s\n" % title)
        for name in names:
            t = tools.get(name)
            if t is None:
                raise SystemExit("docs group lists a tool the server doesn't have: %s" % name)
            out.append("### `%s`\n\n%s\n" % (name, (t.description or "").strip()))
            rows = _param_rows(t.input_schema or {})
            if rows:
                out.append("| Parameter | Type | Required | Default |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    argv = [a for a in (sys.argv[1:] if argv is None else argv) if a != "docs"]
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print("docs/agent_tools.md is stale: run `artpipe agent docs`", file=sys.stderr)
            return 1
        print("docs/agent_tools.md is current")
        return 0
    with OUT.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d tools)" % (OUT.relative_to(ROOT), sum(len(n) for _, n in GROUPS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
