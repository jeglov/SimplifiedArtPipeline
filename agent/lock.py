"""Write agent/requirements.lock from a folder of downloaded wheels (exact versions + sha256).

    <venv python> -m pip download mcp==X pyyaml==Y --only-binary=:all: -d WHEELS
    python agent/lock.py WHEELS

The lock is installed with `pip install --require-hashes --no-deps`, so the
venv gets exactly these files: no resolver, no newer transitive dependency.
It is for CPython 3.12 on win_amd64 (some wheels are binary). Stdlib only.
"""
import hashlib
import re
import sys
from pathlib import Path

LOCK = Path(__file__).resolve().parent / "requirements.lock"
_WHEEL = re.compile(r"^(?P<name>[A-Za-z0-9_.]+)-(?P<version>[^-]+)-")


def main(folder: str) -> int:
    lines = []
    for whl in sorted(Path(folder).glob("*.whl"), key=lambda p: p.name.lower()):
        m = _WHEEL.match(whl.name)
        if not m:
            print("not a wheel name: %s" % whl.name, file=sys.stderr)
            return 2
        name = m.group("name").replace("_", "-").lower()
        digest = hashlib.sha256(whl.read_bytes()).hexdigest()
        lines.append("%s==%s --hash=sha256:%s" % (name, m.group("version"), digest))
    with LOCK.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Generated by agent/lock.py: CPython 3.12, win_amd64. Install with\n"
                 "# pip install --require-hashes --no-deps -r agent/requirements.lock\n")
        fh.write("\n".join(lines) + "\n")
    print("wrote %d pins to %s" % (len(lines), LOCK))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
